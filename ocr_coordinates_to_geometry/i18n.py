def language_code(locale_name: str | None) -> str:
    return "ru" if (locale_name or "").lower().replace("-", "_").startswith("ru") else "en"


def translate(key: str, locale_name: str | None = None, **values) -> str:
    text = RU.get(key, EN.get(key, key)) if language_code(locale_name) == "ru" else EN.get(key, key)
    return text.format(**values) if values else text


